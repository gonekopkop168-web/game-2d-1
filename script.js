let current = 0;

const khmerDigits = n => String(n).replace(/\d/g, d => "០១២៣៤៥៦៧៨៩"[Number(d)]);

function renderMessage() {
  messageEl.textContent = messages[current];
  counterEl.textContent = `សារ ${khmerDigits(current + 1)} ក្នុងចំណោម ${khmerDigits(messages.length)}`;
  progressFill.style.width = `${((current + 1) / messages.length) * 100}%`;
  prevBtn.disabled = current === 0;
  nextBtn.textContent = current === messages.length - 1 ? "ចាប់ផ្ដើមម្ដងទៀត 💗" : "សារបន្ទាប់ 💕 →";
  messageEl.style.animation = "none";
  void messageEl.offsetWidth;
  messageEl.style.animation = "fadeIn .3s ease";
  bigHeart.textContent = ["♥", "♡", "💗", "💕"][current % 4];
}

prevBtn.addEventListener("click", () => {
  if (current > 0) current--;
  renderMessage();
});
nextBtn.addEventListener("click", () => {
  current = current === messages.length - 1 ? 0 : current + 1;
  renderMessage();
});

