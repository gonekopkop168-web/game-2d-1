// Background music: attempt autoplay, repeat forever, and provide a control
// because mobile browsers may block autoplay until the visitor taps the page.
const backgroundAudio = document.getElementById("backgroundAudio");
const musicToggle = document.getElementById("musicToggle");
const musicLabel = document.getElementById("musicLabel");
const musicIcon = document.getElementById("musicIcon");

function updateMusicButton(isPlaying) {
  musicToggle.classList.toggle("playing", isPlaying);
  musicLabel.textContent = isPlaying ? "បិទបទចម្រៀង 🔊" : "បើកបទចម្រៀង 🎵";
  musicIcon.textContent = isPlaying ? "♫" : "♪";
  musicToggle.setAttribute("aria-label", isPlaying ? "បិទតន្ត្រីផ្ទៃខាងក្រោយ" : "បើកតន្ត្រីផ្ទៃខាងក្រោយ");
}

async function startBackgroundMusic() {
  try {
    backgroundAudio.loop = true;
    await backgroundAudio.play();
    updateMusicButton(true);
  } catch (error) {
    // Autoplay can be blocked by browser settings; the button lets the visitor start it.
    updateMusicButton(false);
  }
}

musicToggle.addEventListener("click", async () => {
  if (backgroundAudio.paused) {
    await startBackgroundMusic();
  } else {
    backgroundAudio.pause();
    updateMusicButton(false);
  }
});
backgroundAudio.addEventListener("play", () => updateMusicButton(true));
backgroundAudio.addEventListener("pause", () => updateMusicButton(false));
startBackgroundMusic();
